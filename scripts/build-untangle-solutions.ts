// Precompute Untangle boards and engine-verified solutions for the site.
//
//   npx esbuild scripts/build-untangle-solutions.ts --bundle --platform=node --format=esm \
//     --loader:.json=json --outfile=/tmp/untangle-solutions.mjs
//   node /tmp/untangle-solutions.mjs [shard] [shards]       # search non-hard generator boards
//   node /tmp/untangle-solutions.mjs merge [shards]
//   node /tmp/untangle-solutions.mjs retry [shard] [shards]; ... merge-retry [shards]
//   node /tmp/untangle-solutions.mjs hard [shard] [shards]  # hydrate hard-generator boards with their reverse-scramble oracle
//   node /tmp/untangle-solutions.mjs merge-hard [shards]
//   node /tmp/untangle-solutions.mjs hydrate [shard] [shards]; ... merge-hydrate [shards] # all selected Core boards
//   node /tmp/untangle-solutions.mjs verify                # replay every stored solution as the site does
//   node /tmp/untangle-solutions.mjs add-solves <solves.jsonl> [pool.json]   # store verified human solves
//
// Every board is generated by the vendored engine itself (src/games/vendor/untangle),
// and a solution is kept only if it passes the benchmark's own test: step() each move from
// the restored board with no extra frames in between, and the engine's crossings() is 0.
import { readFileSync, writeFileSync, existsSync, unlinkSync } from 'node:fs';
import { resolve } from 'node:path';
import { UntangleGame } from '../src/games/vendor/untangle/untangle';

// Run from the repository root.
const FILE = resolve('public/games/untangle.json');
const shardFile = (s: number, kind = '') => resolve(`public/games/untangle.${kind}${s}.json`);
const SPACING = 2.2;
type State = [number, number][];
type Move = [number, number]; // [source hole, target hole]

const xy = (id: number, n: number) => {
  const off = ((n - 1) * SPACING) / 2;
  return [Math.floor(id / n) * SPACING - off, (id % n) * SPACING - off];
};

function segDistance(a1: number[], a2: number[], b1: number[], b2: number[]) {
  const ux = a2[0] - a1[0], uy = a2[1] - a1[1], vx = b2[0] - b1[0], vy = b2[1] - b1[1];
  const wx = a1[0] - b1[0], wy = a1[1] - b1[1];
  const aa = ux * ux + uy * uy, bb = ux * vx + uy * vy, cc = vx * vx + vy * vy, dd = ux * wx + uy * wy, ee = vx * wx + vy * wy;
  const det = aa * cc - bb * bb;
  let sc = det < 1e-8 ? 0 : (bb * ee - cc * dd) / det;
  let tc = det < 1e-8 ? (cc > 1e-8 ? ee / cc : 0) : (aa * ee - bb * dd) / det;
  sc = Math.max(0, Math.min(1, sc));
  tc = Math.max(0, Math.min(1, tc));
  return Math.hypot(a1[0] + ux * sc - (b1[0] + vx * tc), a1[1] + uy * sc - (b1[1] + vy * tc));
}

/** Straight-line layout score: [pairs closer than a rope width, -min clearance]. */
function layout(state: State, n: number): [number, number] {
  let close = 0, clearance = Infinity;
  for (let i = 0; i < state.length; i++) {
    for (let j = i + 1; j < state.length; j++) {
      const d = segDistance(xy(state[i][0], n), xy(state[i][1], n), xy(state[j][0], n), xy(state[j][1], n));
      if (d < 0.44) close++;
      clearance = Math.min(clearance, d);
    }
  }
  return [close, -clearance];
}

function moves(state: State, n: number): Move[] {
  const occ = new Set(state.flat());
  const out: Move[] = [];
  for (const [a, b] of state) for (const src of [a, b]) for (let t = 0; t < n * n; t++) if (!occ.has(t)) out.push([src, t]);
  return out;
}

const apply = (s: State, [src, tgt]: Move): State => s.map(([a, b]) => (a === src ? [tgt, b] : b === src ? [a, tgt] : [a, b]) as [number, number]);
const key = (s: State) => s.map(([a, b]) => (a < b ? `${a}-${b}` : `${b}-${a}`)).join('|');
const cmp = (x: number[], y: number[]) => { for (let i = 0; i < x.length; i++) if (x[i] !== y[i]) return x[i] - y[i]; return 0; };

// A plan is replayed as the benchmark scores it: step() after step(), no frames in between
// (step() itself simulates the lift, the carry and 60 frames of settling). The site replays
// stored solutions the same way, then hands the board back to live physics, so a plan is
// kept only if the ropes also stay uncrossed for STABLE_FRAMES more frames (10 s at 60 Hz).
const STABLE_FRAMES = 600;
const stepTo = (engine: any, [src, tgt]: Move) => {
  const n = engine.gridSize;
  engine.step({ src_row: Math.floor(src / n), src_col: src % n, tgt_row: Math.floor(tgt / n), tgt_col: tgt % n });
};
const staysSolved = (engine: any) => {
  if (engine.crossings() !== 0) return false;
  for (let i = 0; i < STABLE_FRAMES; i++) {
    engine.tickPhysics(1 / 60);
    if (engine.crossings() !== 0) return false;
  }
  return true;
};

function assertExpected(inst: any, engine: any) {
  const expected = inst.expectedState;
  if (!expected) return;
  const ropes = engine.ropes.map((r: any) => ({ s: r.startHole.id, e: r.endHole.id, c: r.color }));
  const sameRopes = JSON.stringify(ropes) === JSON.stringify(expected.ropes);
  if (engine.gridSize !== expected.gridSize || !sameRopes || engine.generatorInfo?.signature !== expected.signature) {
    throw new Error(`${inst.id}: regenerated Untangle board does not match the Core source state`);
  }
  if (expected.visualCrossings !== null && expected.visualCrossings !== undefined &&
      engine.crossings() !== expected.visualCrossings) {
    throw new Error(`${inst.id}: visual crossings ${engine.crossings()} != Core ${expected.visualCrossings}`);
  }
  if (expected.logicalCrossings !== null && expected.logicalCrossings !== undefined &&
      engine.logicalCrossings() !== expected.logicalCrossings) {
    throw new Error(`${inst.id}: logical crossings ${engine.logicalCrossings()} != Core ${expected.logicalCrossings}`);
  }
}

function hydrateCore(shard: number, shards: number) {
  const data = JSON.parse(readFileSync(FILE, 'utf8'));
  const out: Record<string, any> = {};
  data.instances.forEach((inst: any, idx: number) => {
    if (idx % shards !== shard) return;
    const cfg = { ...inst.config, animate: true };
    const gen: any = new UntangleGame({ skipInitialReset: true });
    gen.reset({ ...cfg, animate: false });
    assertExpected(inst, gen);
    const snapshot = gen.exportSnapshot();
    const initialCrossings = gen.crossings();
    const scramble = gen.generatorInfo?.scrambleHistory ?? [];
    const plan: Move[] = scramble.slice().reverse().map((m: any) => [m.targetHole, m.sourceHole]);
    const engine: any = new UntangleGame({ skipInitialReset: true });
    engine.restoreSnapshot(cfg, snapshot);
    for (const move of plan) stepTo(engine, move);
    const solution = plan.length && staysSolved(engine) ? plan : null;
    out[inst.id] = { snapshot, solution, initialCrossings };
    console.log(`${inst.id}: Core state verified; ${solution ? `${solution.length}-move oracle verified` : 'no verified oracle'}`);
  });
  writeFileSync(shardFile(shard, 'hydrate'), JSON.stringify(out));
}

function mergeHydrate(shards: number) {
  const data = JSON.parse(readFileSync(FILE, 'utf8'));
  const parts: Record<string, any> = {};
  for (let s = 0; s < shards; s++) {
    const file = shardFile(s, 'hydrate');
    if (!existsSync(file)) throw new Error(`missing hydrate shard ${s}`);
    Object.assign(parts, JSON.parse(readFileSync(file, 'utf8')));
  }
  let solved = 0;
  for (const inst of data.instances) {
    const part = parts[inst.id];
    if (!part) throw new Error(`no hydrated Core state for ${inst.id}`);
    Object.assign(inst, part, { optimal: null });
    if (part.solution) solved++;
  }
  writeFileSync(FILE, JSON.stringify(data));
  for (let s = 0; s < shards; s++) unlinkSync(shardFile(s, 'hydrate'));
  console.log(`hydrated ${data.instances.length} Core boards; ${solved} reverse-scramble solutions verified`);
}
// Optional: UNTANGLE_CACHE=<previous untangle.json> re-verifies its plans instead of searching;
// UNTANGLE_SKIP=<file of ids> marks boards a wider search already failed on.
const cache: Record<string, any> = process.env.UNTANGLE_CACHE
  ? Object.fromEntries(JSON.parse(readFileSync(process.env.UNTANGLE_CACHE, 'utf8')).instances.map((x: any) => [x.id, x]))
  : {};
const skip = new Set(process.env.UNTANGLE_SKIP ? readFileSync(process.env.UNTANGLE_SKIP, 'utf8').split(/\s+/).filter(Boolean) : []);

function main(shard: number, shards: number, retry = false) {
  const data = JSON.parse(readFileSync(FILE, 'utf8'));
  const out: Record<string, any> = {};
  // Core level and generator difficulty are distinct. Search boards whose
  // generator configuration is not hard; hard-generator boards use their
  // reverse-scramble oracle below.
  const pool = data.instances.filter((x: any) => x.config.difficulty !== 'hard' && (!retry || x.solution === null));
  const [WIDTH, BRANCH, DEPTH] = retry ? [8, 70, 10] : [3, 40, 8];
  pool.forEach((inst: any, idx: number) => {
    if (idx % shards !== shard) return;
    const t0 = Date.now();
    const cfg = { ...inst.config, animate: true };
    const engine: any = new UntangleGame({ skipInitialReset: true });
    const cached = cache[inst.id];
    let snapshot = cached?.snapshot;
    if (!snapshot) {
      const gen: any = new UntangleGame({ skipInitialReset: true });
      gen.reset({ ...cfg, animate: false });
      snapshot = gen.exportSnapshot();
    }
    engine.restoreSnapshot(cfg, snapshot);
    const n = engine.gridSize;
    const initialCrossings = engine.crossings();
    const start: State = engine.ropes.map((r: any) => [r.startHole.id, r.endHole.id]);
    let evaluations = 0;
    const play = (plan: Move[]) => {
      engine.restoreSnapshot(cfg, snapshot);
      for (const m of plan) stepTo(engine, m);
      evaluations += plan.length;
      return engine.crossings();
    };
    const robust = (plan: Move[]) => play(plan) === 0 && staysSolved(engine);
    const finish = (solution: Move[] | null, note: string) => {
      out[inst.id] = { snapshot, solution, initialCrossings };
      console.log(`${inst.id.padEnd(32)} ${solution ? `solved in ${solution.length}` : 'NO SOLUTION'} ${note} (${evaluations} engine steps, ${((Date.now() - t0) / 1000).toFixed(1)}s)`);
    };
    if (!retry && cached?.solution && robust(cached.solution)) return finish(cached.solution, '[cached]');
    if (!retry && skip.has(inst.id)) return finish(null, '[skipped]');

    // Phase A: straight-line search for clean layouts, verified on the engine shortest first.
    const candidates: { plan: Move[]; score: [number, number] }[] = [];
    let beam: { state: State; plan: Move[] }[] = [{ state: start, plan: [] }];
    const seen = new Set([key(start)]);
    for (let depth = 1; depth <= Math.min(inst.budget, 3) && candidates.length < 30; depth++) {
      const next: { state: State; plan: Move[]; score: [number, number] }[] = [];
      for (const node of beam) {
        for (const m of moves(node.state, n)) {
          const s = apply(node.state, m);
          const k = key(s);
          if (seen.has(k)) continue;
          seen.add(k);
          const score = layout(s, n);
          const plan = [...node.plan, m];
          if (score[0] === 0) candidates.push({ plan, score });
          next.push({ state: s, plan, score });
        }
      }
      next.sort((a, b) => cmp(a.score, b.score));
      beam = next.slice(0, 300);
    }
    candidates.sort((a, b) => a.plan.length - b.plan.length || cmp(a.score, b.score));
    let solution: Move[] | null = null;
    for (const c of candidates.slice(0, 30)) {
      if (robust(c.plan)) {
        solution = c.plan;
        break;
      }
    }

    // Phase B: beam search scored by the engine's own crossings. Each node keeps an
    // engine snapshot, so scoring a move costs one engine step; any hit is re-verified
    // by replaying the whole plan from the original board, exactly as the browser does.
    if (!solution) {
      const MAX_DEPTH = Math.min(inst.budget, DEPTH);
      engine.restoreSnapshot(cfg, snapshot);
      let nodes: { plan: Move[]; snap: any }[] = [{ plan: [], snap: engine.exportSnapshot() }];
      const tried = new Set<string>();
      for (let depth = 1; depth <= MAX_DEPTH && !solution && nodes.length; depth++) {
        const scored: { plan: Move[]; snap: any; score: number[] }[] = [];
        for (const node of nodes) {
          const state = node.plan.reduce(apply, start);
          const ranked = moves(state, n)
            .map((m) => ({ m, s: layout(apply(state, m), n) }))
            .sort((a, b) => cmp(a.s, b.s))
            .slice(0, BRANCH);
          for (const { m, s } of ranked) {
            const plan = [...node.plan, m];
            const k = key(apply(state, m)) + '#' + plan.length;
            if (tried.has(k)) continue;
            tried.add(k);
            engine.restoreSnapshot(cfg, node.snap);
            stepTo(engine, m);
            evaluations += 1;
            const visual = engine.crossings();
            if (visual === 0 && robust(plan)) {
              solution = plan;
              break;
            }
            scored.push({ plan, snap: engine.exportSnapshot(), score: [visual, engine.logicalCrossings(), ...s] });
          }
          if (solution) break;
        }
        scored.sort((a, b) => cmp(a.score, b.score));
        nodes = scored.slice(0, WIDTH);
      }
    }

    finish(solution, '');
  });
  writeFileSync(shardFile(shard, retry ? 'retry' : ''), JSON.stringify(out));
}

function merge(shards: number, retry = false) {
  const data = JSON.parse(readFileSync(FILE, 'utf8'));
  const parts: Record<string, any> = {};
  for (let s = 0; s < shards; s++) {
    const f = shardFile(s, retry ? 'retry' : '');
    if (!existsSync(f)) throw new Error(`missing shard ${s}`);
    Object.assign(parts, JSON.parse(readFileSync(f, 'utf8')));
  }
  let solved = 0;
  const pool = data.instances.filter((x: any) => x.config.difficulty !== 'hard');
  for (const inst of pool) {
    const p = parts[inst.id];
    if (!p) {
      if (retry) {
        if (inst.solution) solved++;
        continue;
      }
      throw new Error(`no result for ${inst.id}`);
    }
    inst.snapshot = p.snapshot;
    inst.solution = p.solution;
    inst.initialCrossings = p.initialCrossings;
    inst.optimal = null;
    if (p.solution) solved++;
  }
  writeFileSync(FILE, JSON.stringify(data));
  for (let s = 0; s < shards; s++) unlinkSync(shardFile(s, retry ? 'retry' : ''));
  console.log(`merged: ${solved}/${pool.length} non-hard-generator Core boards have an engine-verified solution`);
}

// Hard-generator boards: the reverse-scramble oracle. The generator builds an uncrossed board, scrambles it with
// recorded moves (generatorInfo.scrambleHistory) and then twists a few ropes into a central
// tangle. Undoing the scramble always uncrosses the peg-to-peg lines, but the simulated ropes
// often stay wrapped around each other, so a Hard board is kept only if that per-board plan
// also passes the benchmark's test above.
function hardScan(shard: number, shards: number) {
  const data = JSON.parse(readFileSync(FILE, 'utf8'));
  const out: Record<string, any> = {};
  data.instances
    .filter((x: any) => x.config.difficulty === 'hard')
    .forEach((inst: any, idx: number) => {
      if (idx % shards !== shard) return;
      const cfg = { ...inst.config, animate: true };
      const gen: any = new UntangleGame({ skipInitialReset: true });
      gen.reset(cfg);
      const snapshot = gen.exportSnapshot();
      const initialCrossings = gen.crossings();
      const plan: Move[] = gen.generatorInfo.scrambleHistory.slice().reverse().map((m: any) => [m.targetHole, m.sourceHole]);
      const engine: any = new UntangleGame({ skipInitialReset: true });
      engine.restoreSnapshot(cfg, snapshot);
      for (const m of plan) stepTo(engine, m);
      const ok = staysSolved(engine);
      out[inst.id] = { snapshot, solution: ok ? plan : null, initialCrossings };
      console.log(`${inst.id.padEnd(32)} reverse scramble ${plan.length} moves: ${ok ? 'solves it' : `${engine.crossings()} rope crossings left`}`);
    });
  writeFileSync(shardFile(shard, 'hard'), JSON.stringify(out));
}

function mergeHard(shards: number) {
  const data = JSON.parse(readFileSync(FILE, 'utf8'));
  const parts: Record<string, any> = {};
  for (let s = 0; s < shards; s++) Object.assign(parts, JSON.parse(readFileSync(shardFile(s, 'hard'), 'utf8')));
  let solved = 0;
  const hard = data.instances.filter((x: any) => x.config.difficulty === 'hard');
  for (const inst of hard) {
    const part = parts[inst.id];
    if (!part) throw new Error(`no hard-generator result for ${inst.id}`);
    inst.snapshot = part.snapshot;
    inst.solution = part.solution;
    inst.initialCrossings = part.initialCrossings;
    inst.optimal = null;
    if (part.solution) solved++;
  }
  writeFileSync(FILE, JSON.stringify(data));
  for (let s = 0; s < shards; s++) unlinkSync(shardFile(s, 'hard'));
  console.log(`hard-generator boards: ${solved}/${hard.length} reverse-scramble plans verified; all snapshots retained`);
}

function verify() {
  const data = JSON.parse(readFileSync(FILE, 'utf8'));
  let bad = 0;
  for (const inst of data.instances) {
    if (!inst.solution) continue;
    const engine: any = new UntangleGame({ skipInitialReset: true });
    engine.restoreSnapshot({ ...inst.config, animate: true }, inst.snapshot);
    for (const m of inst.solution) stepTo(engine, m);
    if (!staysSolved(engine)) {
      bad++;
      console.log(`${inst.id}: stored solution leaves ${engine.crossings()} crossings`);
    }
  }
  const solved = data.instances.filter((x: any) => x.solution).length;
  console.log(`${solved - bad}/${solved} stored solutions verified`);
  if (bad) process.exit(1);
}

// Human solves posted by the site's ?record mode, one JSON object per line ({id, moves, solved}).
// The site plays exactly the benchmark's action space, so a solve is just its move list; for each
// board the shortest one that passes the test above becomes its solution (the board is added from
// the pool file if untangle.json does not have it).
function addSolves(solvesFile: string, poolFile?: string) {
  const data = JSON.parse(readFileSync(FILE, 'utf8'));
  const pool = poolFile ? JSON.parse(readFileSync(poolFile, 'utf8')).instances : [];
  const board = (id: string) => data.instances.find((x: any) => x.id === id) ?? pool.find((x: any) => x.id === id);
  const solves = readFileSync(solvesFile, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l))
    .filter((e: any) => e.game === 'untangle' && e.solved)
    .sort((x: any, y: any) => x.moves.length - y.moves.length);
  const done = new Set<string>();
  for (const e of solves) {
    const inst = board(e.id);
    if (done.has(e.id) || !inst?.snapshot) continue;
    const engine: any = new UntangleGame({ skipInitialReset: true });
    engine.restoreSnapshot({ ...inst.config, animate: true }, inst.snapshot);
    const plan: Move[] = e.moves.map((m: any) => [m.src_row * engine.gridSize + m.src_col, m.tgt_row * engine.gridSize + m.tgt_col]);
    for (const m of plan) stepTo(engine, m);
    const ok = staysSolved(engine);
    console.log(`${e.id}: ${plan.length}-move solve ${ok ? 'verified' : `leaves ${engine.crossings()} crossings`}`);
    if (!ok) continue;
    done.add(e.id);
    if (!inst.solution || plan.length <= inst.solution.length) inst.solution = plan;
    if (!data.instances.includes(inst)) data.instances.push(inst);
  }
  writeFileSync(FILE, JSON.stringify(data));
}

const [a, b, c] = process.argv.slice(2);
if (a === 'merge') merge(Number(b ?? 1));
else if (a === 'retry') main(Number(b ?? 0), Number(c ?? 1), true);
else if (a === 'merge-retry') merge(Number(b ?? 1), true);
else if (a === 'verify') verify();
else if (a === 'add-solves') addSolves(b, c);
else if (a === 'hydrate') hydrateCore(Number(b ?? 0), Number(c ?? 1));
else if (a === 'merge-hydrate') mergeHydrate(Number(b ?? 1));
else if (a === 'hard') hardScan(Number(b ?? 0), Number(c ?? 1));
else if (a === 'merge-hard') mergeHard(Number(b ?? 1));
else main(Number(a ?? 0), Number(b ?? 1));
