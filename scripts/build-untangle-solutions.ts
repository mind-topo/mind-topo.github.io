// Precompute Untangle boards and engine-verified solutions for the site.
//
//   npx esbuild scripts/build-untangle-solutions.ts --bundle --platform=node --format=esm \
//     --loader:.json=json --outfile=/tmp/untangle-solutions.mjs
//   node /tmp/untangle-solutions.mjs [shard] [shards]   # from the repo root;     # writes public/games/untangle.<shard>.json
//   node /tmp/untangle-solutions.mjs merge [shards]       # folds the shards into public/games/untangle.json
//   node /tmp/untangle-solutions.mjs retry [shard] [shards]; ... merge-retry [shards]   # wider search on unsolved
//   node /tmp/untangle-solutions.mjs finalize              # drop boards that still have no verified solution
//
// Every board is generated by the vendored engine itself (src/games/vendor/untangle),
// and a solution is kept only if replaying it on the restored snapshot leaves the
// engine's own crossings() at 0, the success test the benchmark uses.
import { readFileSync, writeFileSync, existsSync, unlinkSync } from 'node:fs';
import { resolve } from 'node:path';
import { UntangleGame } from '../src/games/vendor/untangle/untangle';

// Run from the repository root.
const FILE = resolve('public/games/untangle.json');
const shardFile = (s: number, retry = false) => resolve(`public/games/untangle.${retry ? 'retry' : ''}${s}.json`);
const SPACING = 2.2;
type State = [number, number][];
type Move = [number, number]; // [source hole, target hole]

const xy = (id: number, n: number) => {
  const off = ((n - 1) * SPACING) / 2;
  return [Math.floor(id / n) * SPACING - off, (id % n) * SPACING - off];
};

function segDistance(a1: number[], a2: number[], b1: number[], b2: number[]) {
  const ux = a2[0] - a1[0], uy = a2[1] - a1[1], vx = b2[0] - b1[0], vy = b2[1] - b1[1];
  const wx = a1[0] - b1[0], wy = a1[1] - b1[1];
  const aa = ux * ux + uy * uy, bb = ux * vx + uy * vy, cc = vx * vx + vy * vy, dd = ux * wx + uy * wy, ee = vx * wx + vy * wy;
  const det = aa * cc - bb * bb;
  let sc = det < 1e-8 ? 0 : (bb * ee - cc * dd) / det;
  let tc = det < 1e-8 ? (cc > 1e-8 ? ee / cc : 0) : (aa * ee - bb * dd) / det;
  sc = Math.max(0, Math.min(1, sc));
  tc = Math.max(0, Math.min(1, tc));
  return Math.hypot(a1[0] + ux * sc - (b1[0] + vx * tc), a1[1] + uy * sc - (b1[1] + vy * tc));
}

/** Straight-line layout score: [pairs closer than a rope width, -min clearance]. */
function layout(state: State, n: number): [number, number] {
  let close = 0, clearance = Infinity;
  for (let i = 0; i < state.length; i++) {
    for (let j = i + 1; j < state.length; j++) {
      const d = segDistance(xy(state[i][0], n), xy(state[i][1], n), xy(state[j][0], n), xy(state[j][1], n));
      if (d < 0.44) close++;
      clearance = Math.min(clearance, d);
    }
  }
  return [close, -clearance];
}

function moves(state: State, n: number): Move[] {
  const occ = new Set(state.flat());
  const out: Move[] = [];
  for (const [a, b] of state) for (const src of [a, b]) for (let t = 0; t < n * n; t++) if (!occ.has(t)) out.push([src, t]);
  return out;
}

const apply = (s: State, [src, tgt]: Move): State => s.map(([a, b]) => (a === src ? [tgt, b] : b === src ? [a, tgt] : [a, b]) as [number, number]);
const key = (s: State) => s.map(([a, b]) => (a < b ? `${a}-${b}` : `${b}-${a}`)).join('|');
const cmp = (x: number[], y: number[]) => { for (let i = 0; i < x.length; i++) if (x[i] !== y[i]) return x[i] - y[i]; return 0; };

function main(shard: number, shards: number, retry = false) {
  const data = JSON.parse(readFileSync(FILE, 'utf8'));
  const out: Record<string, any> = {};
  // retry: only boards the first pass left unsolved, with a wider and deeper beam.
  const pool = retry ? data.instances.filter((x: any) => x.solution === null) : data.instances;
  const [WIDTH, BRANCH, DEPTH] = retry ? [8, 70, 10] : [3, 40, 8];
  pool.forEach((inst: any, idx: number) => {
    if (idx % shards !== shard) return;
    const t0 = Date.now();
    const cfg = { ...inst.config, animate: false };
    const gen: any = new UntangleGame();
    gen.reset(cfg);
    const snapshot = gen.exportSnapshot();
    const n = gen.gridSize;
    const engine: any = new UntangleGame();
    let evaluations = 0;
    const play = (plan: Move[]) => {
      engine.restoreSnapshot(cfg, snapshot);
      for (const [src, tgt] of plan) {
        engine.step({ src_row: Math.floor(src / n), src_col: src % n, tgt_row: Math.floor(tgt / n), tgt_col: tgt % n });
      }
      evaluations += plan.length;
      return engine.crossings();
    };
    if (play([]) !== gen.crossings()) throw new Error(`${inst.id}: snapshot does not restore the generated board`);
    const start: State = gen.ropes.map((r: any) => [r.startHole.id, r.endHole.id]);

    // Phase A: straight-line search for clean layouts, verified on the engine shortest first.
    const candidates: { plan: Move[]; score: [number, number] }[] = [];
    let beam: { state: State; plan: Move[] }[] = [{ state: start, plan: [] }];
    const seen = new Set([key(start)]);
    for (let depth = 1; depth <= Math.min(inst.budget, 3) && candidates.length < 30; depth++) {
      const next: { state: State; plan: Move[]; score: [number, number] }[] = [];
      for (const node of beam) {
        for (const m of moves(node.state, n)) {
          const s = apply(node.state, m);
          const k = key(s);
          if (seen.has(k)) continue;
          seen.add(k);
          const score = layout(s, n);
          const plan = [...node.plan, m];
          if (score[0] === 0) candidates.push({ plan, score });
          next.push({ state: s, plan, score });
        }
      }
      next.sort((a, b) => cmp(a.score, b.score));
      beam = next.slice(0, 300);
    }
    candidates.sort((a, b) => a.plan.length - b.plan.length || cmp(a.score, b.score));
    let solution: Move[] | null = null;
    for (const c of candidates.slice(0, 30)) {
      if (play(c.plan) === 0) {
        solution = c.plan;
        break;
      }
    }

    // Phase B: beam search scored by the engine's own crossings. Each node keeps an
    // engine snapshot, so scoring a move costs one engine step; any hit is re-verified
    // by replaying the whole plan from the original board, exactly as the browser does.
    if (!solution) {
      const MAX_DEPTH = Math.min(inst.budget, DEPTH);
      let nodes: { plan: Move[]; snap: any }[] = [{ plan: [], snap: snapshot }];
      const tried = new Set<string>();
      for (let depth = 1; depth <= MAX_DEPTH && !solution && nodes.length; depth++) {
        const scored: { plan: Move[]; snap: any; score: number[] }[] = [];
        for (const node of nodes) {
          const state = node.plan.reduce(apply, start);
          const ranked = moves(state, n)
            .map((m) => ({ m, s: layout(apply(state, m), n) }))
            .sort((a, b) => cmp(a.s, b.s))
            .slice(0, BRANCH);
          for (const { m, s } of ranked) {
            const plan = [...node.plan, m];
            const k = key(apply(state, m)) + '#' + plan.length;
            if (tried.has(k)) continue;
            tried.add(k);
            engine.restoreSnapshot(cfg, node.snap);
            engine.step({ src_row: Math.floor(m[0] / n), src_col: m[0] % n, tgt_row: Math.floor(m[1] / n), tgt_col: m[1] % n });
            evaluations += 1;
            const visual = engine.crossings();
            if (visual === 0 && play(plan) === 0) {
              solution = plan;
              break;
            }
            scored.push({ plan, snap: engine.exportSnapshot(), score: [visual, engine.logicalCrossings(), ...s] });
          }
          if (solution) break;
        }
        scored.sort((a, b) => cmp(a.score, b.score));
        nodes = scored.slice(0, WIDTH);
      }
    }

    out[inst.id] = { snapshot, solution };
    console.log(`${inst.id.padEnd(32)} ${solution ? `solved in ${solution.length}` : 'NO SOLUTION'} (${evaluations} engine steps, ${((Date.now() - t0) / 1000).toFixed(1)}s)`);
  });
  writeFileSync(shardFile(shard, retry), JSON.stringify(out));
}

function merge(shards: number, retry = false) {
  const data = JSON.parse(readFileSync(FILE, 'utf8'));
  const parts: Record<string, any> = {};
  for (let s = 0; s < shards; s++) {
    const f = shardFile(s, retry);
    if (!existsSync(f)) throw new Error(`missing shard ${s}`);
    Object.assign(parts, JSON.parse(readFileSync(f, 'utf8')));
  }
  let solved = 0;
  for (const inst of data.instances) {
    const p = parts[inst.id];
    if (!p) {
      if (retry) {
        if (inst.solution) solved++;
        continue;
      }
      throw new Error(`no result for ${inst.id}`);
    }
    inst.snapshot = p.snapshot;
    inst.solution = p.solution;
    inst.optimal = null;
    if (p.solution) solved++;
  }
  writeFileSync(FILE, JSON.stringify(data));
  for (let s = 0; s < shards; s++) unlinkSync(shardFile(s, retry));
  console.log(`merged: ${solved}/${data.instances.length} instances have an engine-verified solution`);
}

// Boards still unsolved after `retry` are dropped by `finalize`, so every board on the site has an answer.
function finalize() {
  const data = JSON.parse(readFileSync(FILE, 'utf8'));
  const before = data.instances.length;
  data.instances = data.instances.filter((x: any) => x.solution);
  writeFileSync(FILE, JSON.stringify(data));
  console.log(`kept ${data.instances.length}/${before} boards with verified solutions`);
}

const [a, b, c] = process.argv.slice(2);
if (a === 'merge') merge(Number(b ?? 1));
else if (a === 'retry') main(Number(b ?? 0), Number(c ?? 1), true);
else if (a === 'merge-retry') merge(Number(b ?? 1), true);
else if (a === 'finalize') finalize();
else main(Number(a ?? 0), Number(b ?? 1));
